/**
 * Selects a diverse batch of movies across different languages and genres
 * prioritizing titles not yet present in MockAPI.
 *
 * @param {Array} existingMovies - The movies currently loaded from MockAPI
 * @param {number} batchSize - How many movies to pick (default: 4)
 * @returns {Array} List of selected movie objects to POST
 */
export function getDiverseSampleBatch(existingMovies = [], batchSize = 4) {
  const existingTitles = new Set(
    existingMovies.map((m) => (m.title || '').trim().toLowerCase())
  );

  // 1. Identify movies not yet added to MockAPI
  const unadded = WORLD_CINEMA_DATASET.filter(
    (movie) => !existingTitles.has(movie.title.trim().toLowerCase())
  );

  // Helper to shuffle an array (Fisher-Yates)
  const shuffle = (arr) => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  };

  // 2. If we have enough unadded movies, pick a diverse set from different languages
  let pool = unadded.length >= batchSize ? shuffle(unadded) : shuffle(WORLD_CINEMA_DATASET);

  const selected = [];
  const usedLanguages = new Set();

  // Try to pick films from different languages first for maximum global diversity
  for (const movie of pool) {
    if (selected.length >= batchSize) break;
    if (!usedLanguages.has(movie.language)) {
      selected.push(movie);
      usedLanguages.add(movie.language);
    }
  }

  // Fill up remaining slots if needed
  for (const movie of pool) {
    if (selected.length >= batchSize) break;
    if (!selected.some((s) => s.title.toLowerCase() === movie.title.toLowerCase())) {
      selected.push(movie);
    }
  }

  return selected.slice(0, batchSize);
}
